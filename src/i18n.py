def get_text(key: str, lang: str = "en_US", **kwargs) -> str:
    lang_dict = LANGUAGES.get(lang, LANGUAGES["en_US"])
    text = lang_dict.get(key, LANGUAGES["en_US"].get(key, key))
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
